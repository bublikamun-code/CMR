"""Взаимоисключающий запуск фоновых задач на одном хосте.

Зачем. Синк почты запускается cron'ом каждые 5 минут, а сам запрос живёт до
120 секунд (``curl -m 120`` в scripts/watchdog_crm.sh). Если синк не уложился
в интервал, следующий прогон стартует ПОВЕРХ него. Раньше оба получали один и
тот же список непрочитанных писем, оба проходили дедупликацию (записи в
логе ещё нет) и оба создавали карточку — так и появились исторические «дубли
карточек» (аудит 2026-09-30, Ф-2).

Почему файл, а не строка в БД. SQLite и так сериализует писателей, но это
не даёт того, что нужно: писатель ждёт освобождения слота и всё равно
проходит. Нужна блокировка вокруг ВСЕЙ работы, включая походы в IMAP, —
то есть вокруг внешнего ресурса, а не вокруг транзакции. Либо в БД нужна
отдельная таблица-лок, либо файл на том же хосте, что и процессы.

Файловый лок выбран потому, что разворачивание однопроцессное: отдельные
воркеры uvicorn на одном хосте всё равно делят один каталог, и ``flock`` их
разводит. Схема не меняется, миграция не нужна, а при переезде на несколько
хостов блокировка перестаёт работать — это осознанный компромисс под
однохостовое развёртывание, а не универсальное решение.
"""

import errno
import os
from contextlib import contextmanager


class LockBusy(Exception):
    """Блокировку держит другой процесс — текущий запуск можно пропустить."""


def _lock_path(name: str, data_dir: str | None = None) -> str:
    base = data_dir or os.environ.get("CRM_DATA_DIR") or "."
    return os.path.join(base, f".{name}.lock")


@contextmanager
def single_instance(name: str, *, data_dir: str | None = None):
    """Войти в критическую секцию или бросить :class:`LockBusy`.

    Блокировка неблокирующая намеренно: ждать вредно. Следующий прогон cron
    и так придёт через 5 минут, и к тому времени предыдущий либо закончит
    импорт, либо упадёт. Ждать означало бы держать HTTP-запрос открытым и
    упереться в ``-m 120``.

    Блокировка снимается при выходе из контекста, включая исключение, — но
    ТОЛЬКО если она была действительно захвачена. Файл создаётся всегда,
    поэтому запустившийся раньше процесс не сможет захватить блокировку
    только потому, что предыдущий ещё не дошёл до ``open``.
    """
    path = _lock_path(name, data_dir)
    os.makedirs(os.path.dirname(path) or ".", exist_ok=True)
    handle = open(path, "a+")
    try:
        try:
            import fcntl

            fcntl.flock(handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        except ImportError:  # pragma: no cover - платформа без flock
            yield handle
            return
        except OSError as exc:
            # errno EWOULDBLOCK/EAGAIN — лок занят. Остальное (нет прав на
            # каталог, нет места) — это не «занято», а поломка: её нельзя
            # молча проглотить иначе фоновые задачи просто перестанут ходить.
            if exc.errno in (errno.EWOULDBLOCK, errno.EAGAIN):
                raise LockBusy(name) from exc
            raise
        try:
            yield handle
        finally:
            fcntl.flock(handle.fileno(), fcntl.LOCK_UN)
    finally:
        handle.close()
