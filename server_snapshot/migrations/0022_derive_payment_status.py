"""0022: payment_status становится вычисляемым (решение владельца 24.10).

Владелец: выбор «Оплачен 100% / Частично / Не оплачен» руками — пустая
операция, статус должен выводиться из денег. Формула — единая точка правды
``services.card_money.derive_payment_status``:

    нет счёта (сумма ≤ 0)              → «Не оплачен»
    покрытие ≥ суммы                   → «Оплачен»
    есть дата отсрочки и счёт открыт   → «Отсрочка»
    есть частичное покрытие            → «Частично»
    иначе                              → «Не оплачен»

Роуты (создание, PATCH /cards/{id}, PATCH /cards/{id}/payment) статус теперь
только вычисляют; поле убрано из CardUpdate/CardPaymentUpdate.

Что делает миграция. Нормализует уже хранящиеся статусы под ту же формулу —
иначе старые ручные проставки («Оплачен» без копейки покрытия, «Не оплачен»
при полном покрытии) жили бы в базе до первого касания карточки и врали в
списках. Пороги зеркалят money_is_zero (копейка — деньги, хвост float — нет):

    total < 0.005                      → нулевой счёт
    paid >= total − 0.005              → счёт покрыт

Идемпотентна: повторный прогон даёт тот же результат. Побочный эффект
осознанный: у карточек, где статус был проставлен руками без денег, он
«слетит» на вычисленный — это и есть исправление пустой операции.
"""


def up(cur):
    cur.execute("""
        UPDATE cards SET payment_status = CASE
            WHEN IFNULL(total_amount, 0) < 0.005 THEN 'Не оплачен'
            WHEN IFNULL(paid_amount, 0) >= total_amount - 0.005 THEN 'Оплачен'
            WHEN payment_due_date IS NOT NULL THEN 'Отсрочка'
            WHEN IFNULL(paid_amount, 0) >= 0.005 THEN 'Частично'
            ELSE 'Не оплачен'
        END
    """)
