"""Константы бэкенда.

Вынос сюда допусков и множеств, которые план Фазы 4 фиксирует как инвариант:
значение в одном месте, правка масштаба — одна строка, а не перебор роутеров.
"""
from datetime import date, datetime
from zoneinfo import ZoneInfo, ZoneInfoNotFoundError

# Денежный допуск. Раньше хардкодом «0.01» размножен по ~20 местам четырёх
# роутеров (сравнение остатков, округление сумм, автоопределение оплаты).
# Деньги на float (решение владельца 2026-09-11), поэтому сравнения идут
# всегда через этот допуск — напрямую float'ы друг с другом не сравнивать.
MONEY_EPSILON = 0.01

# Канон типов товарных документов (дефект A2, план 2026-09-19).
# Зеркалится в schemas.NAKLADNYE_DOC_TYPES — там валидатор, здесь — для
# роутеров и сервисов, которым нужно проверить тип без импорта схемы
# (например, фильтр списка или нормализация в telegram-боте).
TTN_TYPES = ("ТН", "ТТН", "УПД")

# Бизнес-часовой пояс CRM: сроки сделок и «просрочено» — календарные дни
# пользователя, компания работает по минскому времени. Сравнение с UTC-датой
# сервера сдвигало границу «просрочки» на 3 часа (дефект 6 реестра
# V2-WORKPLAN-2026-09-22): в окне 00:00–03:00 MSK вчерашние сделки не считались
# просроченными. НЕ глобальная замена UTC: ключ дня уведомлений и SINCE-фильтр
# почты осознанно в UTC (см. test_notifications_utc.py).
try:
    BUSINESS_TZ = ZoneInfo("Europe/Minsk")
except ZoneInfoNotFoundError:  # окружение без tzdata (slim-образ): локальная дата
    BUSINESS_TZ = None


def business_today() -> date:
    """Текущий бизнес-день по Минску — единственная точка отсчёта календарных сравнений."""
    return datetime.now(BUSINESS_TZ).date() if BUSINESS_TZ else datetime.now().date()
